def normalize_lang(value):
    """Return 'zh' / 'en' for a supported code (case-insensitive), else None."""
    if isinstance(value, str) and value.lower() in LANGS:
        return value.lower()
    return None


def detect_lang():
    """Language for the current request: cookie > Accept-Language > Chinese."""
    saved = normalize_lang(request.cookies.get(COOKIE_NAME))
    if saved:
        return saved
    # Werkzeug falls back to the primary subtag, so en-US -> en and zh-TW -> zh.
    return request.accept_languages.best_match(LANGS, default=DEFAULT_LANG)


def get_lang():
    if not has_request_context():
        return DEFAULT_LANG
    if 'lang' not in g:
        g.lang = detect_lang()
    return g.lang


def t(key, lang=None, **kwargs):
    entry = MESSAGES[key]
    text = entry.get(lang or get_lang()) or entry[DEFAULT_LANG]
    if kwargs:
        if key.endswith('_html'):
            kwargs = {k: escape(v) for k, v in kwargs.items()}
        text = text.format(**kwargs)
    return Markup(text) if key.endswith('_html') else text


def js_messages(lang=None):
    """All ``js.*`` strings for one language, keyed without the prefix."""
    return {key[3:]: t(key, lang) for key in MESSAGES if key.startswith('js.')}


class LazyText:
    """A translation looked up when rendered, for strings defined at import time
    (WTForms labels and validator messages)."""

    __slots__ = ('key',)

    def __init__(self, key):
        self.key = key

    def __str__(self):
        return t(self.key)

    def __html__(self):
        return escape(str(self))

    def __mod__(self, other):        # WTForms does `message % {...}`
        return str(self) % other

    def __eq__(self, other):
        return str(self) == str(other)

    def __hash__(self):
        return hash(self.key)

    def __repr__(self):
        return f'LazyText({self.key!r})'


def init_app(app):
    @app.context_processor
    def inject_i18n():
        lang = get_lang()
        return {
            't': t,
            'lang': lang,
            'html_lang': HTML_LANG[lang],
            'og_locale': OG_LOCALE[lang],
        }

    @app.after_request
    def vary_on_language(response):
        # The same URL renders differently per cookie / Accept-Language.
        response.vary.add('Accept-Language')
        response.vary.add('Cookie')
        return response
